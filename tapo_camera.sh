#!/bin/sh
# Tapo camera service: go2rtc relays the camera's RTSP H.264 stream to the
# browser over WebRTC without transcoding. go2rtc only connects to the camera
# while someone is watching.

PLUGIN_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
. "$PLUGIN_DIR/lib.sh"

SELF="$PLUGIN_DIR/tapo_camera.sh"

mkdir -p /usr/data/logs "$RUN_DIR"
chmod 700 "$RUN_DIR"

cmdline_of() {
    [ -r "/proc/$1/cmdline" ] || return 1
    tr '\000' ' ' < "/proc/$1/cmdline" 2>/dev/null
}

# PIDs of our processes: the supervisor loop, go2rtc, and the legacy Python server.
find_pids() {
    for _file in /proc/[0-9]*/cmdline; do
        _pid="${_file#/proc/}"
        _pid="${_pid%/cmdline}"
        [ "$_pid" = "$$" ] && continue
        case "$(cmdline_of "$_pid")" in
            *"$SELF supervise"*|*"$GO2RTC -config"*|*"$PLUGIN_DIR/tapo_camera.py"*)
                printf '%s\n' "$_pid"
                ;;
        esac
    done
}

is_enabled() {
    [ "$(read_config ENABLED 0)" = "1" ]
}

# yaml_quote STRING: single-quoted YAML scalar.
yaml_quote() {
    printf "'%s'" "$(printf '%s' "$1" | sed "s/'/''/g")"
}

write_go2rtc_config() {
    _host="$(read_config HOST)"
    _port="$(read_config PORT 554)"
    _stream="$(read_config STREAM stream2)"
    _api_port="$(read_config API_PORT 1984)"
    _webrtc_port="$(read_config WEBRTC_PORT 8555)"

    if [ -z "$_host" ]; then
        echo "ERROR: HOST is not set in $CONF" >&2
        return 1
    fi
    for _n in "$_port" "$_api_port" "$_webrtc_port"; do
        is_number "$_n" || { echo "ERROR: PORT, API_PORT and WEBRTC_PORT must be numbers" >&2; return 1; }
    done

    _url="rtsp://$(urlencode "$(read_config USERNAME)"):$(urlencode "$(read_config PASSWORD)")@$_host:$_port/${_stream#/}"

    _candidates="[]"
    if _public="$(public_host)"; then
        _candidates="[ $(yaml_quote "$_public:$_webrtc_port") ]"
    fi

    _tmp="$GO2RTC_CONF.tmp"
    umask 077
    cat > "$_tmp" <<EOF
# Generated by tapo_camera.sh from $CONF on every start. Do not edit.
log:
  format: text
  level: warn
  output: stdout
api:
  listen: ":$_api_port"
  origin: "*"
  # Only the endpoints Mainsail/Fluidd need. This blocks the web UI and the
  # /api/streams and /api/config endpoints, which could add exec: sources.
  allow_paths: [/api/ws, /api/webrtc, /api/frame.jpeg]
rtsp:
  listen: ""
srtp:
  listen: ""
webrtc:
  listen: ":$_webrtc_port"
  candidates: $_candidates
ffmpeg:
  bin: $FFMPEG
streams:
  $STREAM_NAME: $(yaml_quote "$_url")
EOF
    mv "$_tmp" "$GO2RTC_CONF"
}

# Foreground loop that restarts go2rtc if it exits. Started by "start".
supervise() {
    _child=""
    trap '[ -n "$_child" ] && kill "$_child" 2>/dev/null; exit 0' TERM INT

    export LD_LIBRARY_PATH="$FFMPEG_LD${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
    # Keep the Go runtime small on a 128-512 MB printer.
    export GOGC=50
    export GOMEMLIMIT=40MiB

    while :; do
        echo "$(date '+%F %T') starting go2rtc"
        "$GO2RTC" -config "$GO2RTC_CONF" &
        _child=$!
        wait "$_child"
        _rc=$?
        echo "$(date '+%F %T') go2rtc exited with status $_rc, restarting in 5s"
        _child=""
        sleep 5
    done
}

start() {
    ensure_config

    if ! is_enabled; then
        [ -n "$(find_pids)" ] && stop
        echo "tapo_camera disabled (ENABLED != 1)"
        return 0
    fi

    if [ -n "$(find_pids)" ]; then
        echo "tapo_camera already running"
        return 0
    fi

    if [ ! -x "$GO2RTC" ]; then
        chmod 755 "$GO2RTC" 2>/dev/null
        [ -x "$GO2RTC" ] || { echo "ERROR: go2rtc not found: $GO2RTC" >&2; return 1; }
    fi

    write_go2rtc_config || return 1

    [ -f "$LOGFILE" ] && mv -f "$LOGFILE" "$LOGFILE.1"
    echo "Starting Tapo camera (go2rtc)"
    "$SELF" supervise >>"$LOGFILE" 2>&1 </dev/null &
    echo $! > "$PIDFILE"

    sleep 2
    if ! kill -0 "$(cat "$PIDFILE")" 2>/dev/null; then
        echo "ERROR: Tapo camera failed to start, see $LOGFILE" >&2
        rm -f "$PIDFILE"
        return 1
    fi
    echo "tapo_camera started (PID $(cat "$PIDFILE"))"
}

stop() {
    # Supervisor first so it does not respawn go2rtc.
    for _round in 1 2 3; do
        _pids="$(find_pids)"
        [ -n "$_pids" ] || break
        # shellcheck disable=SC2086
        kill $_pids 2>/dev/null
        sleep 1
    done
    _pids="$(find_pids)"
    # shellcheck disable=SC2086
    [ -n "$_pids" ] && kill -9 $_pids 2>/dev/null
    rm -f "$PIDFILE" /tmp/tapo_camera.pid
    echo "tapo_camera stopped"
}

status() {
    if [ -n "$(find_pids)" ]; then
        echo "tapo_camera running"
        return 0
    fi
    echo "tapo_camera stopped"
    return 1
}

case "${1:-}" in
    start) start ;;
    stop) stop ;;
    restart) stop; start ;;
    status) status ;;
    supervise) supervise ;;
    *)
        echo "Usage: $0 {start|stop|restart|status}"
        exit 1
        ;;
esac
